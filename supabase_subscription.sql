-- ASIKERA AI subscription tables. Run this in Supabase SQL Editor.
-- The Streamlit server must use a server-side service_role key stored in Secrets.
-- NEVER expose the service_role key in client-side code or a public repository.

create table if not exists public.payment_requests (
  id bigint generated by default as identity primary key,
  user_email text not null,
  plan text not null check (plan in ('Monthly', 'Quarterly', 'Yearly')),
  payment_method text not null check (payment_method in ('bKash', 'Rocket', 'Binance Pay ID', 'USDT (TRC20)', 'USDT (BEP20 / BNB Smart Chain)')),
  transaction_ref text not null unique,
  amount_bdt integer not null,
  amount_usd numeric(10,2) not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  reviewed_by text,
  reviewed_at timestamptz
);

create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,
  user_email text not null,
  plan text not null check (plan in ('Monthly', 'Quarterly', 'Yearly')),
  status text not null default 'active' check (status in ('active', 'expired', 'cancelled')),
  starts_at timestamptz not null default now(),
  expires_at timestamptz not null,
  approved_by text not null,
  payment_request_id bigint not null unique references public.payment_requests(id),
  created_at timestamptz not null default now()
);

create index if not exists subscriptions_user_status_expiry_idx
  on public.subscriptions (user_email, status, expires_at desc);
create index if not exists payment_requests_status_created_idx
  on public.payment_requests (status, created_at);

create table if not exists public.daily_usage (
  id bigint generated by default as identity primary key,
  user_email text not null,
  usage_date date not null default (now() at time zone 'utc')::date,
  message_count integer not null default 0 check (message_count >= 0),
  created_at timestamptz not null default now(),
  unique (user_email, usage_date)
);

-- These tables are intended for server-side access only. The app uses custom
-- email/password auth, not Supabase Auth, so do not add user-facing policies
-- that trust a client-supplied email. Keep the service_role key server-side.
alter table public.payment_requests enable row level security;
alter table public.subscriptions enable row level security;
alter table public.daily_usage enable row level security;

-- Existing users/chats tables are not modified by this script.
